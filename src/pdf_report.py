from datetime import datetime
from fpdf import FPDF


def build_pdf_report(inputs, prediction, confidence,
                     trust, trust_text,
                     explanations, counterfactual_text,
                     global_top):
    pdf = FPDF()
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()

    # ── Header band
    pdf.set_fill_color(79, 70, 229)
    pdf.rect(0, 0, 210, 34, "F")
    pdf.set_text_color(255, 255, 255)
    pdf.set_font("Helvetica", "B", 18)
    pdf.set_xy(15, 9)
    pdf.cell(0, 8, "Student Risk - Confidential XAI Report", ln=1)
    pdf.set_font("Helvetica", "", 10)
    pdf.set_xy(15, 21)
    pdf.cell(0, 6,
             f"Author: Waznah (Solo)  |  "
             f"{datetime.now().strftime('%d %B %Y, %H:%M')}", ln=1)

    # ── Prediction + Trust
    pdf.set_y(48)
    pdf.set_text_color(30, 27, 75)
    pdf.set_font("Helvetica", "B", 14)
    pdf.cell(0, 8, "1. Prediction & Trust Assessment", ln=1)
    pdf.set_font("Helvetica", "", 11)

    label = "AT-RISK" if prediction == 1 else "LOW-RISK"
    if prediction == 1:
        pdf.set_text_color(153, 27, 27)
    else:
        pdf.set_text_color(22, 101, 52)
    pdf.cell(0, 7, f"Category: {label}   |   Confidence: {confidence:.1%}", ln=1)

    pdf.set_text_color(30, 27, 75)
    pdf.cell(0, 7, f"Trust Score: {trust}/100  ({trust_text})", ln=1)

    # ── Inputs
    pdf.ln(4)
    pdf.set_font("Helvetica", "B", 14)
    pdf.cell(0, 8, "2. Student Input Data", ln=1)
    pdf.set_font("Helvetica", "", 11)
    for k, v in inputs.items():
        pdf.cell(0, 7, f"   {k.replace('_',' ').title()}:  {v}", ln=1)

    # ── Local explanations
    pdf.ln(4)
    pdf.set_font("Helvetica", "B", 14)
    pdf.cell(0, 8, "3. Why This Prediction?", ln=1)
    pdf.set_font("Helvetica", "", 11)
    for i, e in enumerate(explanations, 1):
        pdf.multi_cell(0, 7, f"   {i}. {e.replace('**','')}")

    # ── Counterfactual
    pdf.ln(4)
    pdf.set_font("Helvetica", "B", 14)
    pdf.cell(0, 8, "4. Suggested Intervention", ln=1)
    pdf.set_font("Helvetica", "", 11)
    if counterfactual_text:
        pdf.multi_cell(0, 7, counterfactual_text.replace("**", ""))
    else:
        pdf.multi_cell(0, 7, "No single-feature change flips the prediction.")

    # ── Global
    pdf.ln(4)
    pdf.set_font("Helvetica", "B", 14)
    pdf.cell(0, 8, "5. Global Feature Importance (Top 5)", ln=1)
    pdf.set_font("Helvetica", "", 11)
    for _, row in global_top.head(5).iterrows():
        name = (str(row['feature']).replace('num__','')
                .replace('cat__','').replace('_',' ').title())
        pdf.cell(0, 7, f"   - {name}:  {row['importance']:.4f}", ln=1)

    # ── Disclaimer
    pdf.ln(8)
    pdf.set_fill_color(255, 251, 235)
    pdf.set_draw_color(249, 115, 22)
    pdf.set_text_color(120, 53, 15)
    pdf.set_font("Helvetica", "B", 11)
    pdf.cell(0, 8, "6. Responsible AI Disclaimer", ln=1)
    pdf.set_font("Helvetica", "", 9)
    disclaimer = (
        "This report is generated by a machine learning prototype for research and "
        "educational demonstration purposes only. It is NOT a definitive judgment of "
        "any student's ability, potential, or future outcomes. Predictions reflect "
        "statistical patterns in a public historical dataset and may contain bias.\n\n"
        "The explanations reflect MODEL BEHAVIOR, not causality. Trust scores are a "
        "heuristic, not a guarantee. Counterfactuals describe what would change this "
        "model's output, not what would change real-world outcomes.\n\n"
        "This system is designed to SUPPORT, not replace, professional educational "
        "judgment. Any intervention must be human-led and empathetic. Do not use for "
        "admissions, grading, disciplinary, or high-stakes decisions."
    )
    pdf.multi_cell(0, 5, disclaimer)

    pdf.set_y(-18)
    pdf.set_text_color(120, 120, 120)
    pdf.set_font("Helvetica", "I", 8)
    pdf.cell(0, 5,
             "AI Innovation Hackathon 2026  |  XAI Track  |  Challenge 1  |  Waznah",
             align="C")
    return bytes(pdf.output())
